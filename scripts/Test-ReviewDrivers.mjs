const scripts = path.dirname(fileURLToPath(import.meta.url)), here = path.join(scripts, 'review');
if (process.argv.length !== 4 || process.argv[2] !== '--root' || !path.isAbsolute(process.argv[3])) throw new Error('Supply --root with an absolute owned scratch path.');
const root = path.resolve(process.argv[3]);
