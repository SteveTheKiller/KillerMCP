let checks = 0;
function run(driver, mode, extra = [], expected = 0, environment = {}) {
  const log = path.join(base, `calls-${checks}.jsonl`);
  const args = [path.join(scripts, driver), '--host', process.execPath, '--host-arg', path.join(here, 'stub.mjs'), '--host-arg', mode, '--host-arg', log,
    '--root', path.join(base, `root-${checks}`), '--seed', '17', '--count', '100', '--timeout', '100', '--downloads', downloads, ...extra];
  const result = spawnSync(process.execPath, args, { encoding: 'utf8', timeout: 20000, env: { ...process.env, ...environment } });
  assert.equal(result.status, expected, result.stderr + result.stdout);
  const summary = JSON.parse(result.stdout.trim().split('\n').at(-1));
  const report = JSON.parse(readFileSync(path.join(summary.resultsDirectory, 'results.json'), 'utf8'));
  const calls = existsSync(log) ? readFileSync(log, 'utf8').trim().split('\n').filter(Boolean).map(JSON.parse) : [];
  checks++;
  return { summary, report, calls };
}
